using CSV, DataFrames, DataFramesMeta

COEFS = [:REP, :NOV, :PC, :LP, :RC]
PRIOR_EXPRS = [
    "truncated(Normal(0, 5), lower=0)",
    "truncated(Normal(0, 5), lower=0)",
    "Normal(0, 5)",
    "Normal(0, 5)",
    "Normal(0, 5)",
]

LOOKUP = CSV.read(joinpath(@__DIR__, "lookup.csv"), DataFrame)
MT_SPECS_MAP = Dict(
    row.mt => parse.(Int, split(row.code, "_"))
    for row in eachrow(unique(@select(LOOKUP, :mt, :code)))
)

model_name(specs) = "clogit_" * join(COEFS[specs], "_")

function generate_model_code(specs)
    fname = model_name(specs)
    syms = COEFS[specs]
    priors = PRIOR_EXPRS[specs]
    g = 3  # rep_vars always uses n=3 per predictor group

    prior_lines = join(["    $(sym) ~ $(prior)" for (sym, prior) in zip(syms, priors)], "\n")
    beta_list = join(string.(syms), ", ")

    return """
@model function $(fname)(x, y)
    nrows, ncols = size(x)
    length(y) == nrows || throw(DimensionMismatch("x/y row mismatch"))

    τ ~ Exponential(5)
$(prior_lines)

    β = [$(beta_list)]

    z = +([β[i] .* x[:, k:k+$(g)-1] for (i, k) in enumerate(1:$(g):ncols)]...)
    z .-= maximum(z, dims=2)
    z ./= τ

    for i in eachindex(y)
        p = softmax(z[i, :])
        y[i] ~ Turing.Categorical(p)
    end
end
"""
end

open(joinpath(@__DIR__, "models.jl"), "w") do io
    println(io, "# AUTO-GENERATED by generate_models.jl — do not edit by hand")
    println(io)

    unique_specs = unique(values(MT_SPECS_MAP))
    for specs in unique_specs
        print(io, generate_model_code(specs))
        println(io)
    end

    println(io, "MODEL_FUNCS = Dict{Vector{Int}, Function}(")
    for specs in unique_specs
        println(io, "    $(specs) => $(model_name(specs)),")
    end
    println(io, ")")
    println(io)
    println(io, "MODELS = Dict(mt => MODEL_FUNCS[mspec] for (mt, mspec) in MT_SPECS_MAP)")
end